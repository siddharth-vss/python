# Practice Q3. Check whether a number is positive or negative using if-else

num = int(input("Enter a number: "))

if num >= 0:
    print("Number is Positive")
else:
    print("Number is Negative")

# -------Output (Positive)-------
# Enter a number: 10
# Number is Positive

# -------Output (Negative)-------
# Enter a number: -5
# Number is Negative
